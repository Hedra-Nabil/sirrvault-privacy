  function applyLanguage(language) {
    const lang = translations[language] ? language : 'en';
    const dir = lang === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
    document.body.dir = dir;
    localStorage.setItem('sirrvault_lang', lang);

    document.querySelectorAll('[data-i18n]').forEach((node) => {
      const key = node.getAttribute('data-i18n');
      if (translations[lang][key]) {
        node.textContent = translations[lang][key];
      }
    });

    document.querySelectorAll('[data-lang-toggle]').forEach((button) => {
      button.textContent = translations[lang].lang_toggle;
      button.setAttribute('aria-label', lang === 'ar' ? 'Switch to English' : 'التبديل إلى العربية');
    });
  }

  document.addEventListener('DOMContentLoaded', () => {
    const saved = localStorage.getItem('sirrvault_lang');
    const initial = saved || (navigator.language && navigator.language.startsWith('ar') ? 'ar' : 'en');
    applyLanguage(initial);

    document.querySelectorAll('[data-lang-toggle]').forEach((button) => {
      button.addEventListener('click', () => {
        const next = document.documentElement.lang === 'ar' ? 'en' : 'ar';
        applyLanguage(next);
      });
    });
  });
